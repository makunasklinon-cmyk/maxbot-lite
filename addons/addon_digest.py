"""addon_digest — ДЕМО-АДДОН для maxbot-lite: сводка непрочитанного раз в N минут.

════════════════════════════════════════════════════════════════════════════
ЭТО УЧЕБНЫЙ ПРИМЕР «как написать свой аддон». Скопируй файл, переименуй,
перепиши логику — контракт останется тем же.
════════════════════════════════════════════════════════════════════════════

КОНТРАКТ (всё, что нужно знать):
  • Файл лежит в `addons/` и называется без ведущего «_».
  • Ядро на старте импортит файл и зовёт `register(ctx)` — ОДИН раз.
  • `ctx` — единственная связь с ботом (ядро импортировать НЕ надо):
        ctx.log                  — свой логгер (пишет в общий лог с префиксом)
        ctx.env(key, default)    — значение из .env / окружения (строкой)
        ctx.owner_id             — Telegram id владельца
        ctx.bot / ctx.dp         — объекты aiogram (можно вешать команды)
        ctx.known                — кэш чатов {id: {name,last_message,unread,…}}
        ctx.page()               — текущая страница браузера (нам тут НЕ нужна)
        await ctx.send_owner(txt) — написать владельцу в личку
        ctx.on_message(cb)       — подписка на каждое новое сообщение: cb(chat, why)
        ctx.spawn(coro, name)    — фоновая задача под присмотром (гасится на выходе)
        await ctx.send_text / ctx.open_chat — действия в MAX (нам тут НЕ нужны)

⚠️ Аддон НЕ трогает протокол MAX — только считает то, что бот и так увидел.
Именно поэтому он годится как публичный пример.
"""
import asyncio


def register(ctx):
    """Точка входа. Ядро вызывает её один раз при старте."""
    # Период сводки берём из .env (DIGEST_EVERY_MIN), по умолчанию 30 мин.
    try:
        every_min = max(1, int(ctx.env("DIGEST_EVERY_MIN", "30")))
    except ValueError:
        every_min = 30

    # Копилка: имя чата -> сколько новых сообщений с прошлой сводки.
    # Замыкание вместо глобалок — у каждого аддона своё состояние.
    tally: dict[str, int] = {}

    def on_message(chat: dict, why: str) -> None:
        # Зовётся ядром на КАЖДОЕ новое сообщение. Только копим — не шлём:
        # мгновенные уведомления уже уходят сами, наша задача — периодическая
        # сводка.
        # `why` — обязательная часть сигнатуры колбэка по контракту
        # ctx.on_message (ядро всегда передаёт оба аргумента); этому аддону
        # причина не нужна — считаем ЛЮБОЕ новое сообщение одинаково.
        # Другому аддону `why` может понадобиться, например, чтобы не
        # копить служебные события — тогда сюда добавится `if why != ...`.
        name = chat.get("name") or "?"
        tally[name] = tally.get(name, 0) + 1

    ctx.on_message(on_message)

    # Сколько чатов показываем построчно — остальные уходят одной строкой
    # итога, чтобы заголовок (total) и список никогда не расходились молча.
    TOP_N = 20

    async def digest_loop():
        while True:
            # Весь цикл — под одним try: любая ошибка внутри (не только при
            # отправке) не должна убить фоновую задачу навсегда. `spawn` не
            # перезапускает упавшие задачи сам — если тут вылетит исключение
            # без защиты, сводки замолкнут насовсем и без единого следа в
            # логе. Поэтому ловим здесь, а не только вокруг send_owner.
            try:
                await asyncio.sleep(every_min * 60)
                if not tally:
                    continue                   # тишина — сводку не шлём
                # Снимаем копилку и сразу обнуляем (следующее окно — с нуля).
                snapshot = sorted(tally.items(), key=lambda kv: kv[1],
                                  reverse=True)
                tally.clear()
                total = sum(n for _, n in snapshot)
                lines = [f"🗂 <b>Сводка за {every_min} мин</b>: {total} новых"]
                shown, rest = snapshot[:TOP_N], snapshot[TOP_N:]
                for name, n in shown:
                    lines.append(f"• {name} — {n}")
                if rest:
                    rest_total = sum(n for _, n in rest)
                    lines.append(f"…и ещё {len(rest)} чат(ов), "
                                 f"{rest_total} сообщени(й)")
                await ctx.send_owner("\n".join(lines))
            except Exception as e:
                ctx.log.warning("digest: ошибка в цикле сводки: %r", e)

    ctx.spawn(digest_loop(), name="addon_digest")
    ctx.log.info("digest: сводка раз в %s мин", every_min)

